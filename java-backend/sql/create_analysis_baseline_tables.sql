    KEY idx_method_product_hit_shop (method_id, marketplace, seller_name, hit_status),
    KEY idx_method_product_hit_asin (marketplace, asin)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='方法卡商品命中缓存';
