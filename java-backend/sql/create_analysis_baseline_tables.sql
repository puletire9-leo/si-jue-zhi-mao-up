    KEY idx_shop_profile_positioning_score (baseline_code, batch_date, similarity_score),
    KEY idx_shop_profile_positioning_shop (marketplace, seller_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='店铺画像基线定位结果';

CREATE TABLE IF NOT EXISTS product_family_group (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    family_code VARCHAR(64) NOT NULL COMMENT '商品族编码',
    marketplace VARCHAR(16) NULL COMMENT '站点/国家，可为空表示跨站点',
    family_name VARCHAR(255) NULL COMMENT '商品族名称',
    seed_asin VARCHAR(32) NULL COMMENT '种子ASIN',
    seed_sales_tier VARCHAR(16) NULL COMMENT '种子销量等级',
    category_key VARCHAR(255) NULL COMMENT '类目键',
    title_signature VARCHAR(512) NULL COMMENT '标题核心签名',
    price_min DECIMAL(18,2) NULL COMMENT '价格带下限',
    price_max DECIMAL(18,2) NULL COMMENT '价格带上限',
    evidence_json JSON NULL COMMENT '商品族证据摘要',
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态',
    computed_at DATETIME NULL COMMENT '计算时间',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    UNIQUE KEY uk_product_family_code (family_code),
    KEY idx_product_family_seed (marketplace, seed_asin),
    KEY idx_product_family_category (marketplace, category_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='商品族证据组';

CREATE TABLE IF NOT EXISTS product_family_member (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    family_code VARCHAR(64) NOT NULL COMMENT '商品族编码',
    marketplace VARCHAR(16) NOT NULL COMMENT '站点/国家',
    asin VARCHAR(32) NOT NULL COMMENT 'ASIN',
    parent_asin VARCHAR(32) NULL COMMENT '父ASIN',
    seller_name VARCHAR(255) NULL COMMENT '店铺名',
    seller_id VARCHAR(128) NULL COMMENT '卖家ID',
    source_table VARCHAR(64) NOT NULL COMMENT '来源表',
    source_batch VARCHAR(64) NOT NULL DEFAULT '' COMMENT '来源批次',
    match_type VARCHAR(64) NOT NULL COMMENT 'SAME_ASIN/PARENT_ASIN/TITLE_SIMILAR/ELEMENT_CARRIER',
    match_score DECIMAL(10,4) NULL COMMENT '相似度分数',
    sales_tier VARCHAR(16) NULL COMMENT '销量等级',
    units INT NULL COMMENT '月销量',
    listing_days INT NULL COMMENT '上架天数',
    category_key VARCHAR(255) NULL COMMENT '类目键',
    evidence_json JSON NULL COMMENT '命中证据',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    UNIQUE KEY uk_product_family_member (family_code, marketplace, asin, source_table, source_batch),
    KEY idx_product_family_member_asin (marketplace, asin),
    KEY idx_product_family_member_seller (marketplace, seller_name),
    CONSTRAINT fk_product_family_member_code
        FOREIGN KEY (family_code) REFERENCES product_family_group (family_code)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='商品族证据成员';

CREATE TABLE IF NOT EXISTS method_product_hit (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键',
    method_id VARCHAR(32) NOT NULL COMMENT '方法卡ID',
    marketplace VARCHAR(16) NOT NULL COMMENT '站点/国家',
    asin VARCHAR(32) NOT NULL COMMENT 'ASIN',
    parent_asin VARCHAR(32) NULL COMMENT '父ASIN',
    seller_name VARCHAR(255) NULL COMMENT '店铺名',
    seller_id VARCHAR(128) NULL COMMENT '卖家ID',
    source_table VARCHAR(64) NOT NULL COMMENT '来源表',
    source_batch VARCHAR(64) NOT NULL DEFAULT '' COMMENT '来源批次',
    hit_reason_json JSON NULL COMMENT '命中原因',
    rule_snapshot_json JSON NULL COMMENT '规则快照',
    hit_status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/EXPIRED',
    computed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '计算时间',
