    baseline_avg_abc_ratio DECIMAL(10,4) NOT NULL DEFAULT 0 COMMENT '基线平均ABC占比',
    baseline_avg_d_ratio DECIMAL(10,4) NOT NULL DEFAULT 0 COMMENT '基线平均D占比',
