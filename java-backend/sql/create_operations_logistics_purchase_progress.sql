CREATE TABLE IF NOT EXISTS operations_logistics_purchase_progress (
    id BIGINT NOT NULL AUTO_INCREMENT,
    business_key CHAR(64) NOT NULL COMMENT 'Purchase item biz_key',
    order_sn VARCHAR(64) NOT NULL,
    item_id BIGINT NULL,
    plan_sn VARCHAR(64) NULL,
    ppg_sn VARCHAR(64) NULL COMMENT '采购计划创建批次号（PPG）',
    sku VARCHAR(128) NOT NULL,
    stock_time DATETIME NULL,
    purchase_quantity INT NOT NULL DEFAULT 0,
    received_quantity INT NOT NULL DEFAULT 0,
    available_quantity INT NOT NULL DEFAULT 0 COMMENT '当前可用于发亚马逊的本地仓可用量',
    valid_shipped_quantity INT NOT NULL DEFAULT 0,
    progress_status VARCHAR(32) NOT NULL COMMENT 'PENDING_ARRIVAL/PENDING_SHIPMENT/SHIPPED',
    progress_value DECIMAL(5,4) NOT NULL DEFAULT 0,
    follow_up_status VARCHAR(32) NOT NULL COMMENT '待到货/待发货/已发货',
    association_status VARCHAR(32) NOT NULL DEFAULT 'LINKED',
    source_hash CHAR(64) NOT NULL,
    terminal TINYINT(1) NOT NULL DEFAULT 0,
    calculated_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_operations_logistics_business (business_key),
    KEY idx_operations_logistics_status (terminal, progress_status),
    KEY idx_operations_logistics_order (order_sn),
    KEY idx_operations_logistics_ppg (ppg_sn),
    KEY idx_operations_logistics_sku (sku)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

