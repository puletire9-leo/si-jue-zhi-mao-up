-- Operations logistics: Lingxing shipment facts and normalized purchase progress.

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS lingxing_shipment_plan (
    id BIGINT NOT NULL AUTO_INCREMENT,
    isp_id BIGINT NOT NULL COMMENT 'Lingxing shipment plan item ID',
    ispg_id BIGINT NULL,
    order_sn VARCHAR(64) NULL COMMENT 'Lingxing shipment plan number (R...)',
    seq VARCHAR(64) NULL COMMENT 'Lingxing shipment plan batch (RP...)',
    purchase_order_sn VARCHAR(64) NULL COMMENT 'Locally bound purchase order',
    purchase_plan_sn VARCHAR(64) NULL COMMENT 'Locally bound purchase plan',
    sku VARCHAR(128) NULL,
    msku VARCHAR(255) NULL,
    fnsku VARCHAR(128) NULL,
    product_name VARCHAR(512) NULL,
    product_id BIGINT NULL,
    pic_url VARCHAR(500) NULL,
    small_image_url VARCHAR(500) NULL,
    sid BIGINT NULL,
    sname VARCHAR(255) NULL,
    nation VARCHAR(50) NULL,
    wid BIGINT NULL,
    wname VARCHAR(255) NULL,
    packing_type TINYINT NULL,
    packing_type_name VARCHAR(50) NULL,
    shipment_plan_quantity INT NOT NULL DEFAULT 0,
    shipment_time VARCHAR(32) NULL,
    status INT NULL,
    status_name VARCHAR(64) NULL,
    is_relate_mws TINYINT NOT NULL DEFAULT 0,
    shipment_list_sn VARCHAR(128) NULL,
    shipment_mws_sn VARCHAR(128) NULL,
    batch_remark TEXT NULL,
    remark TEXT NULL,
    create_user VARCHAR(100) NULL,
    create_time_remote DATETIME NULL,
    shipping_method VARCHAR(20) NULL,
    local_created_by_user_id BIGINT NULL,
    local_created_by_username VARCHAR(100) NULL,
    local_created_by_nickname VARCHAR(100) NULL,
    local_created_time DATETIME NULL,
    raw_json LONGTEXT NULL,
    synced_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_lingxing_shipment_plan_isp (isp_id),
    KEY idx_lingxing_shipment_plan_purchase (purchase_order_sn, purchase_plan_sn),
    KEY idx_lingxing_shipment_plan_sku (sku),
    KEY idx_lingxing_shipment_plan_seq (seq)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

